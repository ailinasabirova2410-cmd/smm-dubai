  var PRICES = {"reels": {"AED": [4500, 3500], "USD": [1225, 950], "RUB": [99000, 77000]}, "growth": {"AED": [6900, 5900], "USD": [1880, 1600], "RUB": [152000, 130000]}, "funnel": {"AED": [12500, 9900], "USD": [3400, 2700], "RUB": [275000, 218000]}};

  var CUR_FMT = {
    AED: function (n) { return 'AED ' + n.toLocaleString('en-US'); },
    USD: function (n) { return '$' + n.toLocaleString('en-US'); },
    RUB: function (n) { return n.toLocaleString('ru-RU') + ' ₽'; }
  };

  /* ---- i18n: capture EN from markup, swap by dictionary ---- */
  var EN = {};
  var nodes = document.querySelectorAll('[data-i18n]');
  nodes.forEach(function (el) { EN[el.getAttribute('data-i18n')] = el.innerHTML; });

  var lang = 'en';
  function setLang(next) {
    lang = next === 'ru' ? 'ru' : 'en';
    var dict = lang === 'ru' ? RU : EN;
    nodes.forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (dict[k] != null) el.innerHTML = dict[k];
    });
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-lang]').forEach(function (b) {
      b.classList.toggle('on', b.getAttribute('data-lang') === lang);
    });
    var ta = document.querySelector('textarea[name="message"]');
    var ci = document.querySelector('input[name="contact"]');
    if (ta) ta.placeholder = lang === 'ru' ? 'Ссылка на аккаунт и что сейчас не работает' : "Account link and what's not working";
    if (ci) ci.placeholder = lang === 'ru' ? '@ник или +971…' : '@username or +971…';
  }

  var qs = new URLSearchParams(location.search);
  var initial = qs.get('lang');
  if (initial !== 'ru' && initial !== 'en') {
    initial = (navigator.language || '').toLowerCase().indexOf('ru') === 0 ? 'ru' : 'en';
  }
  if (initial === 'ru') setLang('ru');

  document.querySelectorAll('[data-lang]').forEach(function (b) {
    b.addEventListener('click', function () { setLang(b.getAttribute('data-lang')); });
  });

  /* ---- currency: AED default for every language, not persisted ---- */
  function setCur(cur) {
    if (!PRICES.reels[cur]) cur = 'AED';
    var fmt = CUR_FMT[cur];
    Object.keys(PRICES).forEach(function (plan) {
      var pair = PRICES[plan][cur];
      var o = document.querySelector('[data-old="' + plan + '"]');
      var n = document.querySelector('[data-new="' + plan + '"]');
      if (o) o.textContent = fmt(pair[0]);
      if (n) n.textContent = fmt(pair[1]);
    });
    document.querySelectorAll('[data-cur]').forEach(function (b) {
      b.classList.toggle('on', b.getAttribute('data-cur') === cur);
    });
  }
  setCur('AED');
  document.querySelectorAll('[data-cur]').forEach(function (b) {
    b.addEventListener('click', function () { setCur(b.getAttribute('data-cur')); });
  });

