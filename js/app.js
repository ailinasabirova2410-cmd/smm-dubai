  var sheet = document.getElementById('sheet');
  var burger = document.getElementById('burger');
  if (burger && sheet) {
    burger.addEventListener('click', function () { sheet.hidden = false; document.body.style.overflow = 'hidden'; });
    var close = function () { sheet.hidden = true; document.body.style.overflow = ''; };
    document.getElementById('sheetClose').addEventListener('click', close);
    sheet.querySelectorAll('a[href^="#"]').forEach(function (a) { a.addEventListener('click', close); });
  }

  /* ---- lightbox ---- */
  var lb = document.getElementById('lb');
  var lbImg = document.getElementById('lbImg');
  var lbCap = document.getElementById('lbCap');
  document.querySelectorAll('.shot').forEach(function (btn) {
    btn.addEventListener('click', function () {
      var img = btn.querySelector('img');
      lbImg.src = img.src;
      lbImg.alt = img.alt;
      lbCap.textContent = btn.getAttribute('data-cap') || '';
      lb.hidden = false;
      document.body.style.overflow = 'hidden';
    });
  });
  function lbClose() { lb.hidden = true; lbImg.src = ''; document.body.style.overflow = ''; }
  document.getElementById('lbClose').addEventListener('click', lbClose);
  lb.addEventListener('click', function (e) { if (e.target === lb) lbClose(); });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape' && !lb.hidden) lbClose(); });

  /* ---- reveal on scroll (first screen always visible without JS) ---- */
  var fold = window.innerHeight;
  var rises = [];
  document.querySelectorAll('.rise').forEach(function (el) {
    if (el.getBoundingClientRect().top > fold * 0.9) { el.classList.add('pre'); rises.push(el); }
  });
  if ('IntersectionObserver' in window && rises.length) {
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (en.isIntersecting) { en.target.classList.remove('pre'); io.unobserve(en.target); }
      });
    }, { threshold: 0.12 });
    rises.forEach(function (el) { io.observe(el); });
  } else {
    rises.forEach(function (el) { el.classList.remove('pre'); });
  }

  /* ---- lead form: Netlify Forms, WhatsApp fallback ---- */
  var form = document.getElementById('lead');
